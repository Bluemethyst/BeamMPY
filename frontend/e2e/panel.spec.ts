import { test, expect } from '@playwright/test'
import path from 'node:path'
import { existsSync } from 'node:fs'

test.describe.serial('Multi-instance management through the production HTTP stack', () => {
  test('setup, install, power, console, settings and logout', async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/')
    await expect(page).toHaveURL(/\/setup$/)
    await page.getByLabel('Username', { exact: true }).fill('admin')
    await page.getByLabel('Show password', { exact: true }).check()
    await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text')
    await page.getByLabel('Password', { exact: true }).fill('short')
    expect(await page.getByLabel('Password', { exact: true }).evaluate((input: HTMLInputElement) => input.validity.tooShort)).toBe(true)
    await page.getByLabel('Show password', { exact: true }).uncheck()
    await page.getByLabel('Password', { exact: true }).fill('browser-password-123')
    await page.getByLabel('Confirm password', { exact: true }).fill('browser-password-123')
    await page.getByRole('button', { name: 'Create administrator' }).click()
    await expect(page.getByRole('heading', { name: 'All servers.' })).toBeVisible()
    await page.screenshot({ path: 'test-results/desktop-overview.png', fullPage: true })
    await page.getByRole('button', { name: 'Create server', exact: true }).click()
    await page.getByLabel('Server name', { exact: true }).fill('Browser instance')
    await expect(page.getByLabel('AuthKey', { exact: true })).toHaveAttribute('required', '')
    await expect(page.getByLabel('AuthKey', { exact: true })).toHaveAttribute('maxlength', '256')
    await page.getByRole('button', { name: 'Create and install' }).click()
    await expect(page.getByRole('dialog', { name: 'Create a server' })).toBeVisible()
    expect(await page.getByLabel('AuthKey', { exact: true }).evaluate((input: HTMLInputElement) => input.validity.valueMissing)).toBe(true)
    await page.getByLabel('Port', { exact: true }).fill('1023')
    expect(await page.getByLabel('Port', { exact: true }).evaluate((input: HTMLInputElement) => input.validity.rangeUnderflow)).toBe(true)
    await page.getByLabel('Port', { exact: true }).fill('30814')
    await page.getByLabel('AuthKey', { exact: true }).fill('browser-test-auth-key')
    await page.getByRole('button', { name: 'Create and install' }).click()
    await expect(page.getByRole('heading', { name: 'Browser instance', exact: true })).toBeVisible()
    await expect(page.locator('m3e-snackbar-host').getByRole('status')).toContainText('Instance created')
    await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeEnabled()
    await page.getByRole('button', { name: 'Start', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Stop', exact: true })).toBeEnabled()
    await expect(page.locator('.terminal')).toContainText('READY')
    await page.getByLabel('Console command', { exact: true }).fill('say browser-test')
    await page.getByRole('button', { name: 'Send', exact: true }).click()
    await expect(page.locator('.terminal')).toContainText('ECHO say browser-test')
    await page.screenshot({ path: 'test-results/desktop-console.png', fullPage: true })
    await page.reload()
    await expect(page.locator('.terminal')).toContainText('ECHO say browser-test')
    await page.getByRole('button', { name: 'Restart', exact: true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Restart server', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Stop', exact: true })).toBeEnabled()
    await page.getByRole('tab', { name: 'Console', exact: true }).focus()
    await page.keyboard.press('ArrowRight')
    await expect(page.getByRole('tab', { name: 'Configuration', exact: true })).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('tabpanel', { name: 'Configuration', exact: true })).toBeVisible()
    await expect(page.getByLabel('Server name', { exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Map', exact: true })).toBeDisabled()
    await expect(page.getByRole('switch', { name: 'Private server', exact: true })).toBeDisabled()
    await page.getByRole('tab', { name: 'Console', exact: true }).click()
    await page.getByRole('button', { name: 'Stop', exact: true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Stop server', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Start', exact: true })).toBeEnabled()
    await page.getByRole('tab', { name: 'Configuration', exact: true }).click()
    await page.getByLabel('Description', { exact: true }).fill('Saved by browser')
    const privateSwitch = page.getByRole('switch', { name: 'Private server', exact: true })
    const wasPrivate = await privateSwitch.isChecked()
    await privateSwitch.click()
    await page.getByRole('button', { name: 'Save configuration' }).click()
    await expect(page.getByRole('button', { name: 'Save configuration' })).toBeDisabled()
    await page.reload()
    await expect(page.getByLabel('Description', { exact: true })).toHaveValue('Saved by browser')
    await expect(page.getByRole('switch', { name: 'Private server', exact: true })).toBeChecked({ checked: !wasPrivate })
    await page.getByLabel('Server name', { exact: true }).fill('Unsaved name')
    await page.getByRole('tab', { name: 'Console', exact: true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page).toHaveURL(/\/settings$/)
    await page.getByRole('tab', { name: 'Console', exact: true }).click()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Discard changes' }).click()
    await page.getByRole('button', { name: 'Log out' }).click()
    await expect(page).toHaveURL(/\/login$/)
    expect(errors).toEqual([])
  })

  test('login, import, mobile layout, themes and expired session', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto('/login')
    await page.getByLabel('Username', { exact: true }).fill('admin')
    await page.getByLabel('Password', { exact: true }).fill('browser-password-123')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'All servers.' })).toBeVisible()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: 'Toggle navigation' }).click()
    await expect(page.getByRole('dialog', { name: 'Workspace navigation' }).getByRole('navigation')).toBeVisible()
    await expect(page.locator('.m3e-navigation-drawer--modal')).not.toHaveAttribute('data-animating')
    // The native M3E drawer traps keyboard focus and restores its opener.
    await expect(page.getByRole('link', { name: 'BeamMPY home', exact: true })).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(page.getByRole('dialog', { name: 'Workspace navigation' }).getByRole('button', { name: 'Browser instance', exact: true })).toBeFocused()
    await page.screenshot({ path: 'test-results/mobile-navigation.png' })
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: 'Toggle navigation' })).toBeFocused()
    await page.getByRole('button', { name: 'Color theme', exact: true }).click()
    await page.getByRole('menuitemradio', { name: 'Dark theme', exact: true }).click()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
    await page.screenshot({ path: 'test-results/mobile-dark-overview.png', fullPage: true })
    await page.getByRole('button', { name: 'Color theme', exact: true }).click()
    await page.getByRole('menuitemradio', { name: 'Light theme', exact: true }).click()
    await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
    await page.getByRole('button', { name: 'Import server', exact: true }).click()
    await page.getByLabel('Server name', { exact: true }).fill('Missing import')
    await page.getByLabel('Local folder or ZIP', { exact: true }).check()
    await page.getByLabel('Absolute directory or ZIP path').fill('relative-path')
    await page.getByRole('dialog').getByRole('button', { name: 'Import server', exact: true }).click()
    await expect(page.getByRole('dialog').getByRole('alert')).toContainText('absolute')
    const instances = await (await page.request.get('/api/servers')).json()
    const dataRoot = path.dirname(path.dirname(instances.servers[0].directory))
    await page.getByLabel('Server name', { exact: true }).fill('Imported browser server')
    await page.getByLabel('Absolute directory or ZIP path').fill(path.join(dataRoot, 'import-ready'))
    await page.getByRole('dialog').getByRole('button', { name: 'Import server', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Imported browser server', exact: true })).toBeVisible()
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: 'test-results/mobile-console.png', fullPage: true })
    // Invalidate the actual shared browser session through the HTTP API.
    const session = await (await page.request.get('/api/auth/session')).json()
    await page.request.post('/api/auth/logout', { data: {}, headers: { 'X-CSRF-Token': session.csrf_token } })
    await expect(page).toHaveURL(/\/login$/)
    await page.screenshot({ path: 'test-results/mobile-login.png', fullPage: true })
  })

  test('maps, ZIP mods, browser archive import, and both deletion choices', async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('/login')
    await page.getByLabel('Username', { exact: true }).fill('admin')
    await page.getByLabel('Password', { exact: true }).fill('browser-password-123')
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(page).toHaveURL(/\/servers$/)
    const result = await (await page.request.get('/api/servers')).json()
    const server = result.servers.find((item: any) => item.name === 'Browser instance')
    const dataRoot = path.dirname(path.dirname(server.directory))
    await page.goto(`/servers/${server.id}/settings`)
    await expect(page.locator('.settings-section .eyebrow').first()).toHaveText('IDENTITY')
    const dangerColor = await page.getByRole('button', { name: 'Delete server', exact: true }).evaluate(element => getComputedStyle(element).backgroundColor)
    expect(dangerColor).toMatch(/^rgb\(/)
    const [red, green, blue] = dangerColor.match(/\d+/g)!.map(Number)
    expect(red).toBeGreaterThan(green * 2)
    expect(red).toBeGreaterThan(blue * 2)
    await page.getByRole('tab', { name: 'Maps', exact: true }).click()
    const italy = page.locator('.map-card').filter({ has: page.getByRole('heading', { name: 'Italy', exact: true }) })
    await italy.getByRole('button', { name: 'Use this map' }).click()
    await expect(italy.getByRole('button', { name: 'Selected map' })).toBeVisible()
    await page.getByRole('tab', { name: 'Mods', exact: true }).click()
    await page.getByLabel('Mod ZIP files', { exact: true }).setInputFiles(path.join(dataRoot, 'test-fixtures/browser-trails.zip'))
    await expect(page.getByRole('heading', { name: 'browser-trails.zip', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Disable browser-trails.zip' }).click()
    await expect(page.getByRole('button', { name: 'Enable browser-trails.zip' })).toBeEnabled()
    await page.getByRole('button', { name: 'Enable browser-trails.zip' }).click()
    await expect(page.getByRole('button', { name: 'Disable browser-trails.zip' })).toBeEnabled()
    await page.screenshot({ path: 'test-results/mod-manager.png', fullPage: true })
    await page.getByRole('tab', { name: 'Maps', exact: true }).click()
    const canyon = page.locator('.map-card').filter({ has: page.getByRole('heading', { name: 'Browser Canyon', exact: true }) })
    await canyon.getByRole('button', { name: 'Use this map' }).click()
    await expect(canyon.getByRole('button', { name: 'Selected map' })).toBeVisible()
    await page.screenshot({ path: 'test-results/map-manager.png', fullPage: true })
    await page.getByRole('tab', { name: 'Configuration', exact: true }).click()
    await expect(page.getByLabel('Map', { exact: true })).toHaveText(/Browser Canyon/)
    await page.getByRole('button', { name: 'Map', exact: true }).click()
    await expect(page.getByRole('menu', { name: 'Map options', exact: true })).toBeVisible()
    await page.keyboard.press('Home')
    await page.keyboard.press('ArrowDown')
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Save configuration' })).toBeEnabled()
    await page.getByRole('button', { name: 'Save configuration' }).click()
    await expect(page.getByRole('button', { name: 'Save configuration' })).toBeDisabled()
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: 'test-results/mobile-settings.png', fullPage: true })
    await page.setViewportSize({ width: 320, height: 740 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.setViewportSize({ width: 1280, height: 720 })
    await page.goto('/servers')
    await page.getByRole('button', { name: 'Import server', exact: true }).click()
    await page.getByLabel('Server name', { exact: true }).fill('Uploaded browser server')
    await page.getByLabel('Upload ZIP', { exact: true }).check()
    await page.getByLabel('Server ZIP archive', { exact: true }).setInputFiles(path.join(dataRoot, 'test-fixtures/server-archive.zip'))
    await page.getByRole('dialog').getByRole('button', { name: 'Import server', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Uploaded browser server', exact: true })).toBeVisible()
    const uploadedList = await (await page.request.get('/api/servers')).json()
    const imported = uploadedList.servers.find((item: any) => item.name === 'Uploaded browser server')
    await page.getByRole('tab', { name: 'Configuration', exact: true }).click()
    await page.getByRole('button', { name: 'Delete server', exact: true }).click()
    await expect(page.getByRole('alertdialog').getByRole('button', { name: 'Delete server', exact: true })).toBeDisabled()
    await page.getByLabel('Type the server name to confirm').fill('Uploaded browser server')
    await page.getByRole('alertdialog').getByRole('button', { name: 'Delete server', exact: true }).click()
    await expect(page).toHaveURL(/\/servers$/)
    expect(existsSync(imported.directory)).toBe(true)
    await page.getByRole('button', { name: 'Import server', exact: true }).click()
    await page.getByLabel('Server name', { exact: true }).fill('Delete files instance')
    await page.getByLabel('Local folder or ZIP', { exact: true }).check()
    await page.getByLabel('Absolute directory or ZIP path').fill(imported.directory)
    await page.getByRole('dialog').getByRole('button', { name: 'Import server', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Delete files instance', exact: true })).toBeVisible()
    await page.getByRole('tab', { name: 'Configuration', exact: true }).click()
    await page.getByRole('button', { name: 'Delete server', exact: true }).click()
    await page.getByLabel('Type the server name to confirm').fill('Delete files instance')
    await page.getByLabel('Also permanently delete the instance files').check()
    await page.getByRole('alertdialog').getByRole('button', { name: 'Delete server', exact: true }).click()
    await expect(page).toHaveURL(/\/servers$/)
    expect(existsSync(imported.directory)).toBe(false)
    expect(existsSync(path.join(dataRoot, 'test-fixtures/server-archive.zip'))).toBe(true)
    expect(errors).toEqual([])
  })
})
